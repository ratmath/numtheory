const BITS = 192;
const REG_LOW = 0.2052; // E. Friedman, Analytic formulas for the regulator of a number field, Invent. Math. 98 (1989)
const REG_LOW_PER_ROOT = 0.09058; // R/w ≥ 0.09058, same paper

/** ⌊the Minkowski bound⌋: every ideal class contains an integral ideal of norm at most this. */
export function minkowskiBound(K) {
  const O = ringOfIntegers(K);
  const n = BigInt(O.n);
  const r2 = O.signature[1];
  let fact = 1n;
  for (let i = 2n; i <= n; i++) fact *= i;
  // bound² = (n!/nⁿ)² (4/π)^(2r₂) |d|, and 4/π < 1273239545/10⁹
  const num = fact * fact * abs(O.discriminant) * 1273239545n ** BigInt(2 * r2);
  const den = n ** (2n * n) * 10n ** BigInt(18 * r2);
  return isqrt(num / den);
}

// ---- embeddings ----

function embeddings(O) {
  if (O._emb) return O._emb;
  const n = O.n;
  const [r1] = O.signature;
  const B = BigInt(BITS);
  const one = 1n << B;
  const { real, complex } = rootsFixed(O.T, r1, BITS);
  const places = [...real.map((x) => [x, 0n]), ...complex];
  // ωᵢ at each place
  const om = places.map(([re, im]) => {
    const pw = [[one, 0n]];
    for (let j = 1; j < n; j++) {
      const [a, b] = pw[j - 1];
      pw.push([(a * re - b * im) >> B, (a * im + b * re) >> B]);
    }
    return O.W.map((row) => {
      let x = 0n;
      let y = 0n;
      for (let j = 0; j < n; j++) {
        x += row[j] * pw[j][0];
        y += row[j] * pw[j][1];
      }
      return [x / O.dW, y / O.dW];
    });
  });
  const embed = (v) =>
    om.map((w) => {
      let x = 0n;
      let y = 0n;
      for (let i = 0; i < n; i++) {
        if (v[i] === 0n) continue;
        x += v[i] * w[i][0];
        y += v[i] * w[i][1];
      }
      return [x, y];
    });
  // ln|σ(x)| at a real place, 2·ln|σ(x)| at a complex one
  const logVec = (v) =>
    embed(v).map(([x, y], k) => (k < r1 ? lnFixed(x < 0n ? -x : x, BITS) : lnFixed((x * x + y * y) >> B, BITS)));
  // integer coordinates for the T₂ norm
  const SH = B - 24n;
  const t2 = (v) => embed(v).flatMap(([x, y], k) => (k < r1 ? [x >> SH] : [x >> SH, y >> SH]));
  return (O._emb = { places, embed, logVec, t2, r1 });
}
/** A basis of the lattice spanned by the rows (order coordinates) that is LLL-reduced for the T₂ norm. */
function reducedBasis(O, rows) {
  const n = O.n;
  const { t2 } = embeddings(O);
  const A = rows.map((row, i) => [...t2(row), ...unitVec(i, n)]);
  return lllInt(A).map((r) => rowTimes(r.slice(n), rows));
}
/** Σ cᵢbᵢ with max |cᵢ| = C, up to sign, coefficients without a common factor. */
function* smallCombos(basis, C, cap = Infinity) {
  const n = basis.length;
  const c = new Array(n).fill(-C);
  let count = 0;
  for (;;) {
    let ok = c.some((x) => x === C || x === -C);
    if (ok) {
      const first = c.find((x) => x !== 0);
      ok = first > 0;
    }
    if (ok) {
      let g = 0;
      for (const x of c) {
        let a = Math.abs(x);
        let b = g;
        while (b) [a, b] = [b, a % b];
        g = a;
      }
      ok = g === 1;
    }
    if (ok) {
      const v = new Array(basis[0].length).fill(0n);
      for (let i = 0; i < n; i++) {
        if (!c[i]) continue;
        const ci = BigInt(c[i]);
        for (let j = 0; j < v.length; j++) v[j] += ci * basis[i][j];
      }
      yield v;
      if (++count >= cap) return;
    }
    let k = 0;
    while (k < n && c[k] === C) c[k++] = -C;
    if (k === n) return;
    c[k]++;
  }
}

// ---- Smith normal form with the column transformation ----

function smith(M) {
  const k = M.length;
  const A = M.map((r) => r.slice());
  const V = identity(k);
  const Vi = identity(k);
  const swapCols = (a, b) => {
    if (a === b) return;
    for (const r of A) [r[a], r[b]] = [r[b], r[a]];
    for (const r of V) [r[a], r[b]] = [r[b], r[a]];
    [Vi[a], Vi[b]] = [Vi[b], Vi[a]];
  };
  const ab = (x) => (x < 0n ? -x : x);
  for (let t = 0; t < k; t++) {
    for (;;) {
      let pi = -1;
      let pj = -1;
      for (let i = t; i < k; i++) for (let j = t; j < k; j++) if (A[i][j] !== 0n && (pi < 0 || ab(A[i][j]) < ab(A[pi][pj]))) [pi, pj] = [i, j];
      [A[t], A[pi]] = [A[pi], A[t]];
      swapCols(t, pj);
      const p = A[t][t];
      let clean = true;
      for (let i = t + 1; i < k; i++) {
        const q = A[i][t] / p;
        if (q !== 0n) for (let j = t; j < k; j++) A[i][j] -= q * A[t][j];
        if (A[i][t] !== 0n) clean = false;
      }
      for (let j = t + 1; j < k; j++) {
        const q = A[t][j] / p;
        if (q !== 0n) {
          for (const r of A) r[j] -= q * r[t];
          for (const r of V) r[j] -= q * r[t];
          for (let c = 0; c < k; c++) Vi[t][c] += q * Vi[j][c];
        }
        if (A[t][j] !== 0n) clean = false;
      }
      if (!clean) continue;
      let bad = -1;
      for (let i = t + 1; i < k && bad < 0; i++) for (let j = t + 1; j < k; j++) if (A[i][j] % p !== 0n) bad = i;
      if (bad < 0) break;
      for (let j = t; j < k; j++) A[t][j] += A[bad][j];
    }
    if (A[t][t] < 0n) for (let j = t; j < k; j++) A[t][j] = -A[t][j];
  }
  return { d: A.map((r, i) => r[i]), V, Vi };
}

// ---- roots of unity ----

function torsion(O) {
  const n = O.n;
  const one = unitVec(0, n);
  if (O.signature[0] > 0) return { w: 2, zeta: one.map((x) => -x) };
  let g = 0n;
  let q = BigInt(n + 1);
  for (let count = 0; count < 24; ) {
    q = nextPrime(q);
    if (O.polyDiscriminant % q === 0n) continue;
    for (const f of factorModP(O.T, q)) g = gcd(g, q ** BigInt(f.length - 1) - 1n);
    count++;
  }
  let w = 1;
  let zeta = O.field.one;
  const phi = (m) => {
    let r = 0;
    for (let a = 1; a <= m; a++) {
      let [x, y] = [a, m];
      while (y) [x, y] = [y, x % y];
      if (x === 1) r++;
    }
    return r;
  };
  for (const { prime, exponent } of factor(g)) {
    if (prime > BigInt(n + 1)) continue;
    for (let e = exponent; e >= 1; e--) {
      const m = Number(prime) ** e;
      if (n % phi(m) !== 0) continue;
      const roots = rootsIn(O.field, cyclotomic(m));
      if (roots.length) {
        zeta = zeta.mul(roots[0].value);
        w *= m;
        break;
      }
    }
  }
  return { w, zeta: O._coords(zeta).v };
}

// ---- the computation ----

const SMALLP = 65521;

class Search {
  constructor(O, options) {
    this.O = O;
    const n = O.n;
    this.r = O.signature[0] + O.signature[1] - 1;
    this.M = minkowskiBound(O);
    const maxBound = BigInt(options.maxBound ?? 2000);
    if (this.M > maxBound) refuse("too-large", `the Minkowski bound ${this.M} is above ${maxBound}; raise option maxBound to go on`);
    const limit = this.M > BigInt(2 * n + 5) ? this.M : BigInt(2 * n + 5);
    this.limit = limit;
    this.ratPrimes = primeList(limit);
    this.FB = [];
    this.fbIndex = new Map();
    for (const p of this.ratPrimes) {
      const ids = [];
      for (const P of O.primesAbove(p)) {
        ids.push(this.FB.length);
        this.FB.push(P);
      }
      this.fbIndex.set(p, ids);
    }
    this.k = this.FB.length;
    this.rels = [];
    this.seen = new Set();
    this.echelon = []; // rows mod SMALLP with pivots, for a quick rank
    this.spare = 0;
    this.tested = 0;
    this.budget = options.budget ?? 400000;
    this.tors = torsion(O);
  }
  rowOf(v, N) {
    // the exponents of (v) over the factor base, or null when it does not factor there
    let rest = N;
    const ps = [];
    for (const p of this.ratPrimes) {
      if (rest % p === 0n) {
        ps.push(p);
        do rest /= p;
        while (rest % p === 0n);
        if (rest === 1n) break;
      }
    }
    if (rest !== 1n) return null;
    const row = new Array(this.k).fill(0);
    for (const p of ps) for (const i of this.fbIndex.get(p)) row[i] = this.FB[i]._valInt(v);
    return row;
  }
  tryElement(v) {
    const key = v.join(",");
    if (this.seen.has(key)) return false;
    this.seen.add(key);
    this.tested++;
    const N = abs(this.O._norm(v));
    if (N === 0n) return false;
    const row = this.rowOf(v, N);
    if (!row) return false;
    // quick rank mod a small prime
    let w = row.map((x) => ((x % SMALLP) + SMALLP) % SMALLP);
    for (const { piv, vec } of this.echelon) {
      const f = w[piv];
      if (f) w = w.map((x, j) => (x - ((f * vec[j]) % SMALLP) + SMALLP) % SMALLP);
    }
    const piv = w.findIndex((x) => x !== 0);
    if (piv >= 0) {
      let inv = 1;
      for (let e = SMALLP - 2, b = w[piv]; e > 0; e >>= 1, b = (b * b) % SMALLP) if (e & 1) inv = (inv * b) % SMALLP;
      this.echelon.push({ piv, vec: w.map((x) => (x * inv) % SMALLP) });
    } else {
      if (this.spare >= this.r + this.extra + 24) return false;
      this.spare++;
    }
    this.rels.push({ v, row });
    return true;
  }
  *candidates() {
    const O = this.O;
    const n = O.n;
    const C0 = n <= 2 ? 7 : n === 3 ? 3 : n === 4 ? 2 : 1;
    const B0 = reducedBasis(O, identity(n));
    // the rational primes themselves: p·O = ∏ P^e ties the primes above p together
    for (const p of this.ratPrimes) yield unitVec(0, n).map((x) => x * p);
    for (let C = 1; C <= C0; C++) yield* smallCombos(B0, C);
    const order = this.FB.map((P, i) => i).sort((a, b) => (this.FB[a].norm < this.FB[b].norm ? -1 : this.FB[a].norm > this.FB[b].norm ? 1 : 0));
    const bases = new Map();
    const basisOf = (i) => {
      if (!bases.has(i)) bases.set(i, reducedBasis(O, this.FB[i].toIdeal().H));
      return bases.get(i);
    };
    const cap = n <= 4 ? Infinity : 400;
    for (let C = 1; ; C++) {
      for (const i of order) if (this.FB[i].f < n) yield* smallCombos(basisOf(i), C, cap);
      yield* smallCombos(B0, C0 + C, 4000);
      // products of two primes of the factor base
      if (C >= 2) {
        for (let a = 0; a < order.length; a++) {
          const b = (a * 7 + C * 3 + 1) % order.length;
          const I = this.FB[order[a]].toIdeal().mul(this.FB[order[b]].toIdeal());
          yield* smallCombos(reducedBasis(O, I.H), C - 1, cap);
        }
      }
    }
  }
  /** Reduce the relation lattice: null when more relations are needed. */
  analyse() {
    const { O, k, r, rels } = this;
    const m = rels.length;
    const { logVec } = embeddings(O);
    let Y = null;
    let Bs = null;
    for (const C of [1 << 12, 1 << 18, 1 << 24]) {
      const red = lllFloat(rels.map((rel, i) => [...rel.row.map((x) => x * C), ...Array.from({ length: m }, (_, j) => (i === j ? 1 : 0))]));
      Y = [];
      Bs = [];
      let safe = true;
      for (const row of red) {
        if (row.some((x) => !Number.isSafeInteger(x))) safe = false;
        if (row.slice(0, k).every((x) => x === 0)) Y.push(row.slice(k));
        else Bs.push({ img: row.slice(0, k).map((x) => BigInt(x / C)), t: row.slice(k) });
      }
      if (safe && Bs.length === k) break;
      Bs = null;
    }
    if (!Bs) return null;
    const Bmat = Bs.map((b) => b.img);
    const hdet = abs(det(Bmat));
    if (hdet === 0n) return null;
    // check the transformation exactly
    const image = (t) => {
      const out = new Array(k).fill(0n);
      t.forEach((c, i) => {
        if (c) for (let j = 0; j < k; j++) out[j] += BigInt(c) * BigInt(rels[i].row[j]);
      });
      return out;
    };
    for (const y of Y) if (!isZeroVec(image(y))) throw new Error("a kernel vector failed its check");
    for (const b of Bs) if (image(b.t).some((x, j) => x !== b.img[j])) throw new Error("a lattice vector failed its check");
    // units from the kernel
    const logs = rels.map((rel) => (rel.log ??= logVec(rel.v)));
    const places = logs[0].length;
    const logOf = (y) => {
      const s = new Array(places).fill(0n);
      y.forEach((c, i) => {
        if (c) for (let j = 0; j < places; j++) s[j] += BigInt(c) * logs[i][j];
      });
      return s;
    };
    const unitRows = r > 0 && Y.length ? unitLattice(Y.map(logOf), r) : [];
    if (!unitRows) return null;
    const units = unitRows.map((t) => {
      const y = new Array(m).fill(0n);
      t.forEach((c, i) => {
        if (c !== 0n) for (let j = 0; j < m; j++) y[j] += c * BigInt(Y[i][j]);
      });
      let u = this.product(y);
      if (u.d !== 1n || abs(O._norm(u.v)) !== 1n) throw new Error("a kernel element is not a unit");
      let inv = O._coords(O._element(u.v).inv());
      let lg = logOf(y.map(Number));
      // of u, −u, 1/u, −1/u keep the one that reads best: fewest negative coefficients, then smallest
      const score = (v) => {
        const cs = O._element(v).coefficients();
        const negs = cs.filter((c) => c.numerator < 0n).length;
        return [negs, v.reduce((s, c) => s + abs(c), 0n)];
      };
      const better = (a, b) => a[0] < b[0] || (a[0] === b[0] && a[1] < b[1]);
      let best = { v: u.v, inv: inv.v, flip: false, sc: score(u.v) };
      for (const cand of [
        { v: u.v.map((x) => -x), inv: inv.v.map((x) => -x), flip: false },
        { v: inv.v, inv: u.v, flip: true },
        { v: inv.v.map((x) => -x), inv: u.v.map((x) => -x), flip: true },
      ]) {
        cand.sc = score(cand.v);
        if (better(cand.sc, best.sc)) best = cand;
      }
      u = { v: best.v };
      inv = { v: best.inv };
      if (best.flip) lg = lg.map((x) => -x);
      return { v: u.v, inv: inv.v, log: lg.map((x) => fixedToNumber(x, BITS)) };
    });
    const regulator = r === 0 ? 1 : Math.abs(detNumber(units.map((u) => u.log.slice(0, r))));
    if (!(regulator > 1e-9)) return null;
    return { Bs, Bmat, h: hdet, units, regulator, m };
  }
  /** ∏ xᵢ^eᵢ over the relation elements, as coordinates { v, d }. */
  product(exps) {
    const O = this.O;
    let num = unitVec(0, O.n);
    let den = unitVec(0, O.n);
    exps.forEach((e, i) => {
      if (e === 0n) return;
      const x = powCoords(O, this.rels[i].v, e < 0n ? -e : e);
      if (e > 0n) num = O._mul(num, x);
      else den = O._mul(den, x);
    });
    if (den.every((x, i) => x === (i === 0 ? 1n : 0n))) return { v: num, d: 1n };
    return O._coords(O._element(num).div(O._element(den)));
  }
  /**
   * Is the group ℓ-saturated: no element outside its ℓ-th powers is an ℓ-th power in the field?
   * `which` is "all" (the group generated by the relation elements and the roots of unity, inside
   * the S-units) or "units" (the units found, inside all units).
   */
  saturated(l, res, which) {
    const { O, k, r, rels } = this;
    const L = BigInt(l);
    res._gens ??= {};
    if (!res._gens[which]) {
      // "all": the relation elements and the root of unity; "units": the fundamental units and the root of unity
      const gens = which === "all" ? [...rels.slice(0, res.m).map((x) => x.v), this.tors.zeta] : [...res.units.map((u) => u.v), this.tors.zeta];
      const small = gens.every((v) => v.every((x) => x > -(1n << 50n) && x < 1n << 50n));
      res._gens[which] = { gens, small, gnum: small ? gens.map((v) => Float64Array.from(v, Number)) : null };
    }
    const { gens, small, gnum } = res._gens[which];
    const G = gens.length;
    const target = (which === "all" ? k : 0) + r + (this.tors.w % l === 0 ? 1 : 0);
    const n = O.n;
    const ech = []; // reduced rows (Int32Array over the generators) with their pivots
    let rank = 0;
    let cols = 0;
    let q = this.limit > L ? this.limit - (this.limit % L) + 1n : 1n;
    const vec = new Int32Array(G);
    while (rank < target) {
      q += L;
      if (q <= this.limit || O.polyDiscriminant % q === 0n || !isPrime(q)) continue;
      // every root of T mod q: each is a prime of degree 1 (taking only one would bias the choice)
      let Tq = O.T.map((c) => ((c % q) + q) % q);
      const roots = [];
      for (;;) {
        const t = Tq.length > 2 ? oneRoot(Tq, q) : Tq.length === 2 ? (q - Tq[0]) % q : null;
        if (t === null) break;
        roots.push(t);
        const quo = new Array(Tq.length - 1).fill(0n);
        let carry = 0n;
        for (let i = Tq.length - 1; i >= 1; i--) {
          carry = (Tq[i] + carry * t) % q;
          quo[i - 1] = carry;
        }
        Tq = quo;
      }
      const fast = small && q < 1n << 26n;
      const qn = Number(q);
      for (const t of roots) {
        if (rank >= target) break;
        // ωᵢ at the root
        const dinv = powmod(O.dW, q - 2n, q);
        const pw = [1n];
        for (let j = 1; j < n; j++) pw.push((pw[j - 1] * t) % q);
        const wv = O.W.map((row) => (((row.reduce((s, c, j) => s + c * pw[j], 0n) % q) + q) % q * dinv) % q);
        const e = (q - 1n) / L;
        if (fast) {
          const mulm = (a, b) => (a * b) % qn;
          const pown = (a, ex) => {
            let res1 = 1;
            while (ex > 0) {
              if (ex & 1) res1 = mulm(res1, a);
              a = mulm(a, a);
              ex = Math.floor(ex / 2);
            }
            return res1;
          };
          const en = Number(e);
          let hgen = 1;
          for (let g0 = 2; hgen === 1; g0++) hgen = pown(g0, en);
          // baby steps sized for G lookups: about 2·√(ℓ·G) operations in all
          const s = Math.min(l, Math.ceil(Math.sqrt(l * G)));
          const giants = Math.ceil(l / s);
          const baby = new Map();
          let cur = 1;
          for (let j = 0; j < s; j++) {
            baby.set(cur, j);
            cur = mulm(cur, hgen);
          }
          const giant = pown(hgen, qn - 1 - s);
          const wn = Float64Array.from(wv, Number);
          for (let g = 0; g < G; g++) {
            const v = gnum[g];
            let x = 0;
            for (let i = 0; i < n; i++) x = (x + (((v[i] % qn) + qn) % qn) * wn[i]) % qn;
            if (x === 0) throw new Error("a relation element vanishes at an outside prime");
            let y = pown(x, en);
            let d = -1;
            for (let i = 0; i <= giants; i++) {
              const j = baby.get(y);
              if (j !== undefined) {
                d = (i * s + j) % l;
                break;
              }
              y = mulm(y, giant);
            }
            if (d < 0) throw new Error("discrete logarithm failed");
            vec[g] = d;
          }
        } else {
          let hgen = 1n;
          for (let g0 = 2n; hgen === 1n; g0++) hgen = powmod(g0, e, q);
          // baby steps sized for G lookups: about 2·√(ℓ·G) operations in all
          const s = Math.min(l, Math.ceil(Math.sqrt(l * G)));
          const giants = Math.ceil(l / s);
          const baby = new Map();
          let cur = 1n;
          for (let j = 0; j < s; j++) {
            baby.set(cur, j);
            cur = (cur * hgen) % q;
          }
          const giant = powmod(hgen, q - 1n - BigInt(s), q);
          for (let g = 0; g < G; g++) {
            const v = gens[g];
            let x = 0n;
            for (let i = 0; i < n; i++) x += v[i] * wv[i];
            x = ((x % q) + q) % q;
            if (x === 0n) throw new Error("a relation element vanishes at an outside prime");
            let y = powmod(x, e, q);
            let d = -1;
            for (let i = 0; i <= giants; i++) {
              const j = baby.get(y);
              if (j !== undefined) {
                d = (i * s + j) % l;
                break;
              }
              y = (y * giant) % q;
            }
            if (d < 0) throw new Error("discrete logarithm failed");
            vec[g] = d;
          }
        }
        cols++;
        for (const { piv, row } of ech) {
          const f = vec[piv];
          if (f) for (let j = 0; j < G; j++) vec[j] = (vec[j] + (l - f) * row[j]) % l;
        }
        let piv = -1;
        for (let j = 0; j < G; j++) {
          if (vec[j] !== 0) {
            piv = j;
            break;
          }
        }
        if (piv >= 0) {
          const inv = Number(powmod(BigInt(vec[piv]), L - 2n, L)) || 1;
          const row = new Int32Array(G);
          for (let j = 0; j < G; j++) row[j] = (vec[j] * inv) % l;
          ech.push({ piv, row });
          rank++;
        }
      }
      if (cols > 3 * target + 60) return false;
    }
    return true;
  }
}
/**
 * A basis of the lattice spanned by real vectors of rank r (fixed point, the
 * log embeddings of units), as integer combinations of the given vectors.
 * The vectors are written exactly as rational combinations of r independent
 * ones, so that the reduction is done on exact integers; null when the rank
 * is below r.
 */
function unitLattice(L, r) {
  const B = BigInt(BITS);
  const one = 1n << B;
  const num = L.map((row) => row.slice(0, r).map((x) => fixedToNumber(x, BITS)));
  // r numerically independent rows, by Gram–Schmidt
  const pick = [];
  const ortho = [];
  for (let j = 0; j < L.length && pick.length < r; j++) {
    const v = num[j].slice();
    for (const o of ortho) {
      const f = v.reduce((s, x, i) => s + x * o[i], 0) / o.reduce((s, x) => s + x * x, 0);
      for (let i = 0; i < r; i++) v[i] -= f * o[i];
    }
    const size = Math.hypot(...num[j]);
    if (size > 1e-12 && Math.hypot(...v) > 1e-6 * size) {
      pick.push(j);
      ortho.push(v);
    }
  }
  if (pick.length < r) return null;
  // the inverse of the picked rows, in fixed point
  const A = pick.map((j, i) => [...L[j].slice(0, r), ...unitVec(i, r).map((x) => x * one)]);
  const ab = (x) => (x < 0n ? -x : x);
  for (let c = 0; c < r; c++) {
    let p = c;
    for (let i = c + 1; i < r; i++) if (ab(A[i][c]) > ab(A[p][c])) p = i;
    [A[c], A[p]] = [A[p], A[c]];
    const pv = A[c][c];
    A[c] = A[c].map((x) => (x << B) / pv);
    for (let i = 0; i < r; i++) {
      if (i === c) continue;
      const f = A[i][c];
      if (f !== 0n) A[i] = A[i].map((x, j) => x - ((f * A[c][j]) >> B));
    }
  }
  const inv = A.map((row) => row.slice(r));
  // every row as a rational combination of the picked ones
  const coords = [];
  let den = 1n;
  for (const row of L) {
    const c = [];
    for (let i = 0; i < r; i++) {
      let x = 0n;
      for (let j = 0; j < r; j++) x += row[j] * inv[j][i];
      const q = recognise(x >> B, B);
      if (!q) throw new Error("a unit logarithm is not a rational combination of the others to the working precision");
      c.push(q);
      den = (den * q[1]) / gcd(den, q[1]);
    }
    coords.push(c);
  }
  const W = 1n << 30n;
  const rows = coords.map((c, i) => [...c.map(([a, b]) => W * a * (den / b)), ...unitVec(i, L.length)]);
  const red = rows.length > 1 ? lllInt(rows) : rows;
  const out = red.filter((row) => row.slice(0, r).some((x) => x !== 0n)).map((row) => row.slice(r));
  if (out.length !== r) throw new Error("the unit lattice did not reduce to its rank");
  return out;
}
/** A fixed-point real as a fraction with a small denominator, or null. */
function recognise(x, B) {
  const neg = x < 0n;
  if (neg) x = -x;
  const one = 1n << B;
  const tol = 1n << (B - 90n);
  let [p0, q0, p1, q1] = [0n, 1n, 1n, 0n];
  let [a, b] = [x, one];
  for (let it = 0; it < 200 && b !== 0n; it++) {
    const t = a / b;
    [p0, q0, p1, q1] = [p1, q1, t * p1 + p0, t * q1 + q0];
    [a, b] = [b, a - t * b];
    if (q1 > 1n << 50n) return null;
    const err = x * q1 - p1 * one;
    if ((err < 0n ? -err : err) < tol) return [neg ? -p1 : p1, q1];
  }
  return null;
}
function powCoords(O, v, e) {
  let r = unitVec(0, O.n);
  let b = v;
  while (e > 0n) {
    if (e & 1n) r = O._mul(r, b);
    e >>= 1n;
    if (e) b = O._mul(b, b);
  }
  return r;
}
function detNumber(M) {
  const n = M.length;
  if (!n) return 1;
  const A = M.map((r) => r.slice());
  let d = 1;
  for (let c = 0; c < n; c++) {
    let p = c;
    for (let i = c + 1; i < n; i++) if (Math.abs(A[i][c]) > Math.abs(A[p][c])) p = i;
    if (A[p][c] === 0) return 0;
    if (p !== c) {
      [A[p], A[c]] = [A[c], A[p]];
      d = -d;
    }
    d *= A[c][c];
    for (let i = c + 1; i < n; i++) {
      const f = A[i][c] / A[c][c];
      for (let j = c; j < n; j++) A[i][j] -= f * A[c][j];
    }
  }
  return d;
}

const dataCache = new WeakMap();

function compute(O, options) {
  const n = O.n;
  if (n === 1) {
    return { O, trivial: true, h: 1n, units: [], regulator: 1, tors: { w: 2, zeta: [-1n] }, proven: true, certificate: { method: "the rationals: unique factorisation, units ±1" }, FB: [], Bs: [], Bmat: [], rels: [], M: 1n };
  }
  const S = new Search(O, options);
  S.extra = 6;
  let forms = null;
  if (n === 2) forms = quadraticByForms(O);
  let rounds = 0;
  let last = null;
  let failedAt = null;
  let stall = 0;
  let analysedAt = -1;
  const maxPrime = options.maxIndexPrime ?? 20000;
  for (const v of S.candidates()) {
    if (S.tested > S.budget) {
      if (last) break;
      refuse("budget", `no full set of relations after ${S.tested} elements; raise option budget`);
    }
    if (!S.tryElement(v)) {
      // relations are scarce (inert primes, large norms): go on with what there is
      if (S.echelon.length < S.k || ++stall % 3000 !== 0 || S.rels.length === analysedAt) continue;
    } else {
      stall = 0;
      if (S.echelon.length < S.k || S.rels.length < S.k + S.r + S.extra) continue;
    }
    analysedAt = S.rels.length;
    const res = S.analyse();
    if (!res) {
      S.extra += 4;
      continue;
    }
    last = res;
    let certificate;
    let ok = true;
    if (forms) {
      ok = res.h === forms.h && Math.abs(res.regulator / forms.regulator - 1) < 1e-9;
      certificate = { method: "binary quadratic forms", narrowClassNumber: forms.narrow, formClassNumber: forms.h, minkowskiBound: S.M, relations: res.m };
    } else if (options.certify === false) {
      ok = false;
      rounds = Infinity;
      certificate = { method: "relations only, not certified", minkowskiBound: S.M, relations: res.m };
    } else {
      // [found : true] = (h′/h)·(R′/R). A prime ℓ can divide h′/h only if it divides h′: those ℓ get the
      // full test. Any other ℓ can only divide R′/R ≤ R′/low, and the units alone are tested up to that bound.
      const low = Math.max(REG_LOW, REG_LOW_PER_ROOT * S.tors.w);
      const B = Math.floor((1.0001 * res.regulator) / low);
      const hPrimes = res.h > 1n ? factor(res.h).map((f) => Number(f.prime)) : [];
      certificate = { method: "saturation", minkowskiBound: S.M, relations: res.m, regulatorLowerBound: low, unitIndexBound: B, classNumberPrimes: hPrimes, primesChecked: 0 };
      if (B > maxPrime || hPrimes.some((l) => l > maxPrime)) {
        ok = false;
        rounds = Infinity;
        certificate.note = `the index bound ${B} is above option maxIndexPrime = ${maxPrime}; the result is not certified`;
      } else {
        for (const l of hPrimes) {
          if (!S.saturated(l, res, "all")) {
            ok = false;
            failedAt = l;
            break;
          }
          certificate.primesChecked++;
        }
        for (const l of ok && S.r > 0 ? primeList(B).map(Number) : []) {
          if (hPrimes.includes(l)) continue;
          if (!S.saturated(l, res, "units")) {
            ok = false;
            failedAt = l;
            break;
          }
          certificate.primesChecked++;
        }
      }
    }
    if (ok) return finish(S, res, true, certificate, forms);
    if (++rounds > (options.rounds ?? 6)) {
      certificate.note ??= forms ? "the relations did not reach the class number given by forms" : `saturation at ${failedAt} did not succeed: the class number shown is a multiple of the true one`;
      return finish(S, res, false, certificate, forms);
    }
    S.extra = S.rels.length - S.k - S.r + 6;
  }
  return finish(S, last, false, { method: "relations only", note: "the search budget ran out before certification" }, forms);
}
function quadraticByForms(O) {
  const D = O.discriminant;
  const cg = formClassGroup(D);
  if (D < 0n) return { narrow: cg.h, h: cg.h, regulator: 1, cg };
  const d = D % 4n === 0n ? D / 4n : D;
  const { unit, norm } = fundamentalUnit(d);
  // the field element lives in NumberField.quadratic(d); read its coordinates x + y√d and embed by hand
  const [x, y] = unit.coefficients();
  const reg = Math.abs(Math.log(Math.abs(ratNum(x) + ratNum(y) * Math.sqrt(Number(d)))));
  return { narrow: cg.h, h: norm === -1 ? cg.h : cg.h / 2n, regulator: reg, cg, unitNorm: norm };
}
const ratNum = (q) => {
  const sh = Math.max(0, q.numerator.toString(2).length - 1000, q.denominator.toString(2).length - 1000);
  return Number(q.numerator >> BigInt(sh)) / Number(q.denominator >> BigInt(sh));
};

function finish(S, res, proven, certificate, forms) {
  const { O, FB, k } = S;
  const H = hnfLower(res.Bmat, k);
  const { d, V, Vi } = smith(H);
  const idx = d.map((x, i) => i).filter((i) => d[i] !== 1n);
  const { inv: Binv, den: Bden } = inverseInt(res.Bmat);
  return { O, S, h: res.h, units: res.units, regulator: res.regulator, tors: S.tors, proven, certificate, FB, Bs: res.Bs, Bmat: res.Bmat, Binv, Bden, d, V, Vi, idx, M: S.M, forms, m: res.m };
}

function dataFor(K, options = {}) {
  const O = ringOfIntegers(K);
  const key = JSON.stringify(options);
  if (!dataCache.has(O)) dataCache.set(O, new Map());
  const byKey = dataCache.get(O);
  if (!byKey.has(key)) byKey.set(key, compute(O, options));
  return byKey.get(key);
}

