export class ClassGroup {
  constructor(data) {
    const { O } = data;
    this._d = data;
    this.order = O;
    this.field = O.field;
    /** The class number. */
    this.h = data.h;
    /** Invariant factors d₁ | d₂ | …: the group is the product of cyclic groups of these orders. */
    this.structure = data.trivial ? [] : data.idx.map((i) => data.d[i]);
    /** True when the class number and structure are proven. */
    this.proven = data.proven;
    this.certificate = data.certificate;
    this.minkowskiBound = data.M;
    /** The prime ideals used as generators: all primes above the rational primes up to the bound. */
    this.factorBase = data.FB;
  }
  /** One ideal for each cyclic factor, of small norm, whose class generates it. */
  get generators() {
    if (this._gens) return this._gens;
    const D = this._d;
    if (D.trivial) return (this._gens = []);
    const { O } = D;
    this._gens = D.idx.map((i) => {
      const a = reduceByLattice(D, D.Vi[i]);
      let I = O.unitIdeal;
      a.forEach((e, j) => {
        if (e !== 0n) I = I.mul(D.FB[j].toIdeal().pow(Number(e)));
      });
      return smallRepresentative(O, I);
    });
    return this._gens;
  }
  /** Write an ideal as (α)·∏ P^(−a) over the factor base: { alpha, a }. */
  _reduce(I) {
    const D = this._d;
    const { O, S } = D;
    I = O.ideal(I);
    const rows = I.H;
    const NI = rows.reduce((s, r, i) => s * r[i], 1n);
    const basis = reducedBasis(O, rows);
    const vI = (P) => {
      let best = Infinity;
      for (const row of rows) best = Math.min(best, P._valInt(row));
      return best;
    };
    for (let C = 1; C < 60; C++) {
      for (const v of smallCombos(basis, C)) {
        const N = abs(O._norm(v));
        const q = N / NI;
        let rest = q;
        for (const p of S.ratPrimes) while (rest % p === 0n) rest /= p;
        if (rest !== 1n) continue;
        const a = new Array(D.FB.length).fill(0n);
        D.FB.forEach((P, i) => {
          if (N % P.p === 0n) a[i] = BigInt(P._valInt(v) - vI(P));
        });
        return { alpha: { v, d: I.d }, a };
      }
    }
    throw new Error("no smooth element found in the ideal");
  }
  /** The class of an ideal: its exponents on the generators, each reduced modulo the matching invariant factor. */
  classOf(I) {
    const D = this._d;
    if (D.trivial) return [];
    const { a } = this._reduce(I);
    const c = rowTimes(a.map((x) => -x), D.V);
    return D.idx.map((i) => ((c[i] % D.d[i]) + D.d[i]) % D.d[i]);
  }
  /** { principal, generator }: whether the ideal is principal, with a generator when it is. */
  isPrincipal(I) {
    const D = this._d;
    const { O } = D;
    I = O.ideal(I);
    if (D.trivial) return { principal: true, generator: O.field.of(I.norm) };
    const { alpha, a } = this._reduce(I);
    // ∏ P^a = (γ) exactly when a is in the relation lattice
    const c = rowTimes(a, D.Binv);
    if (c.some((x) => x % D.Bden !== 0n)) return { principal: false, generator: null };
    const exps = new Array(D.m).fill(0n);
    c.forEach((cj, j) => {
      const q = cj / D.Bden;
      if (q !== 0n) D.Bs[j].t.forEach((t, i) => (exps[i] += q * BigInt(t)));
    });
    const gamma = D.S.product(exps);
    const g = O._element(alpha.v, alpha.d).div(O._element(gamma.v, gamma.d));
    return { principal: true, generator: g };
  }
  /** The order of the class of an ideal. */
  orderOf(I) {
    const c = this.classOf(I);
    let o = 1n;
    c.forEach((x, i) => {
      const di = this.structure[i];
      const part = di / gcd(di, x);
      o = (o * part) / gcd(o, part);
    });
    return o;
  }
  toString() {
    const s = this.structure.length ? this.structure.map((d) => `C${d}`).join(" × ") : "trivial";
    return `class group of ${this.field}: ${s}, h = ${this.h}${this.proven ? "" : " (not certified)"}`;
  }
}
function reduceByLattice(D, a) {
  // a minus the nearest lattice vector (Babai rounding in the reduced basis)
  const c = rowTimes(a, D.Binv).map((x) => {
    const t = 2n * x + D.Bden;
    const q = t / (2n * D.Bden);
    return t % (2n * D.Bden) !== 0n && t < 0n ? q - 1n : q;
  });
  const sub = rowTimes(c, D.Bmat);
  return a.map((x, i) => x - sub[i]);
}
function smallRepresentative(O, I) {
  // an integral ideal of small norm in the class of I: α·I for a short α in I⁻¹
  if (I.isOne) return I;
  const J = I.inverse();
  const basis = reducedBasis(O, J.H);
  let best = null;
  let tried = 0;
  for (const v of smallCombos(basis, 1)) {
    if (++tried > 60) break;
    const cand = O.ideal({ v, d: J.d }).mul(I);
    if (!best || cand.norm.compareTo(best.norm) < 0) best = cand;
  }
  return best;
}

export class UnitGroup {
  constructor(data) {
    const { O } = data;
    this._d = data;
    this.order = O;
    this.field = O.field;
    /** The rank r₁ + r₂ − 1 (Dirichlet). */
    this.rank = O.signature[0] + O.signature[1] - 1;
    /** The number of roots of unity in the field. */
    this.torsionOrder = data.tors.w;
    /** A generator of the roots of unity. */
    this.rootOfUnity = O._element(data.tors.zeta);
    /** Fundamental units: with the root of unity they generate every unit. */
    this.fundamentalUnits = data.units.map((u) => O._element(u.v));
    /** The regulator, to double precision. */
    this.regulator = data.regulator;
    this.proven = data.proven;
    this.certificate = data.certificate;
  }
  /** Is x a unit of the ring of integers? */
  isUnit(x) {
    const { v, d } = this.order._coords(x);
    return d === 1n && abs(this.order._norm(v)) === 1n;
  }
  /** Write a unit as ζ^t · ∏ εᵢ^eᵢ: { torsion: t, exponents: [eᵢ] }. */
  exponents(u) {
    if (!this.isUnit(u)) refuse("bad-argument", "not a unit of the ring of integers");
    const D = this._d;
    const O = this.order;
    const r = this.rank;
    let v = O._coords(u).v;
    let es = [];
    if (r > 0) {
      const lg = embeddings(O)
        .logVec(v)
        .map((x) => fixedToNumber(x, BITS));
      // solve Σ eⱼ·log εⱼ = log u on the first r places
      const A = Array.from({ length: r }, (_, i) => [...D.units.map((un) => un.log[i]), lg[i]]);
      for (let c = 0; c < r; c++) {
        let p = c;
        for (let i = c + 1; i < r; i++) if (Math.abs(A[i][c]) > Math.abs(A[p][c])) p = i;
        [A[c], A[p]] = [A[p], A[c]];
        for (let i = 0; i < r; i++) {
          if (i === c) continue;
          const f = A[i][c] / A[c][c];
          for (let j = c; j <= r; j++) A[i][j] -= f * A[c][j];
        }
      }
      es = A.map((row, i) => BigInt(Math.round(row[r] / row[i])));
      es.forEach((e, j) => {
        if (e !== 0n) v = O._mul(v, powCoords(O, e > 0n ? D.units[j].inv : D.units[j].v, e < 0n ? -e : e));
      });
    }
    let z = unitVec(0, O.n);
    for (let t = 0; t < D.tors.w; t++) {
      if (z.every((x, i) => x === v[i])) return { torsion: t, exponents: es };
      z = O._mul(z, D.tors.zeta);
    }
    throw new Error("the unit did not resolve on the fundamental units");
  }
  toString() {
    return `units of ${this.field}: ⟨${this.rootOfUnity}⟩ of order ${this.torsionOrder}${this.fundamentalUnits.length ? ` × ⟨${this.fundamentalUnits.join("⟩ × ⟨")}⟩` : ""}, regulator ${this.regulator}`;
  }
}

