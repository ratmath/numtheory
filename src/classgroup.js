// Class groups and unit groups of number fields.
//
// The method is the classical one made rigorous without any hypothesis:
//   1. Every ideal class contains an ideal of norm at most the Minkowski
//      bound, so the primes above the rational primes up to that bound
//      generate the class group.
//   2. Elements of small norm that factor over those primes give relations
//      between them; the relation lattice Λ has index h′ in Zᵏ and its kernel
//      gives units, with regulator R′. Then h′R′ is a multiple of hR.
//   3. The index of what was found in the truth is (h′/h)·(R′/R). A group G
//      is ℓ-saturated when no element of G outside Gℓ is an ℓ-th power in
//      the field; this is proved by reducing modulo prime ideals of degree 1,
//      which gives characters G/Gℓ → Z/ℓ: as many independent ones as the
//      dimension of G/Gℓ settle it. For each prime ℓ dividing h′ the group
//      generated by all relation elements and the roots of unity is shown
//      ℓ-saturated, so ℓ divides neither factor. Any other prime could only
//      divide R′/R, which is at most R′/0.2052 (Friedman's lower bound for
//      regulators); for those ℓ up to that bound the units found are shown
//      ℓ-saturated. Then h′ = h and R′ = R.
// Quadratic fields are settled through binary quadratic forms instead: the
// class number from reduced forms and the unit from the continued fraction
// must agree with what the relations give.

