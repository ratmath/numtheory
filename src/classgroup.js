/**
 * The ideal of the quadratic field of discriminant D that matches a primitive
 * form (a, b, c) of that discriminant: a·Z + ((−b + √D)/2)·Z. Classes of forms
 * go to (narrow) classes of ideals, and composition to multiplication.
 */
export function formToIdeal(f, K) {
  f = form(f);
  const D = f.discriminant;
  const O = ringOfIntegers(K ?? quadraticFieldOf(D));
  if (O.n !== 2 || O.discriminant !== D) refuse("bad-argument", `the form has discriminant ${D}, which is not the discriminant ${O.discriminant} of the field`);
  // √D in the field: α² = d with D = d or 4d
  const m = O.field.m; // x² + m1·x + m0, monic
  if (m[1][0] !== 0n) refuse("unsupported", "formToIdeal expects the field as Q(√d), from NumberField.quadratic(d)");
  const d = -m[0][0];
  const s = D === d ? 1n : 2n;
  const el = O.field.of([[-f.b, 2n], [s, 2n]]);
  return O.ideal(f.a, el);
}
const quadCache = new Map();
function quadraticFieldOf(D) {
  const d = D % 4n === 0n ? D / 4n : D;
  if (!quadCache.has(d)) quadCache.set(d, NumberField.quadratic(d));
  return quadCache.get(d);
}

